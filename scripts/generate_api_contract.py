            "Este capitulo cierra el recorrido iniciado por runtimes, tools, skills, "
            "agents, systems, environments y evals.\n"
            "\n\n**Lugar en el modelo:** este cap\u00edtulo no a\u00f1ade "
            "c\u00f3mputo; verifica que todas las superficies publicadas describen "
