def _source_path(source: str) -> str:
    module = source.split(":", 1)[0]
    if not module.startswith("agentic_systems"):
        return module
    parts = module.split(".")[1:]
    suffix = "/".join(parts) + ".py" if parts else "__init__.py"
    return "src/agentic_systems/" + suffix


def _api_doc(original: str, manifest: dict[str, Any]) -> str:
    start_marker = "## Complete Public API Index"
    end_marker = "## Provider Conformance API"
    start = original.index(start_marker)
    end = original.index(end_marker, start)
    exports = [entry["id"] for entry in manifest["entries"] if entry["member"] is None]
    block = [
        start_marker,
        "",
        "This block is generated from `agentic_systems.api_contract()`.",
        "It is the exact stable top-level API; CI rejects any difference.",
        "",
        "```text",
        *exports,
        "```",
        "",
        f"Contract entries including public members: {manifest['entry_count']}",
        f"Shared contract scenarios: {manifest['scenario_count']}",
        "",
        f"Contract checksum: `{manifest['checksum']}`",
        "",
    ]
    return original[:start] + "\n".join(block) + original[end:]


def _contract_doc(manifest: dict[str, Any]) -> str:
    lines = [
        "# Agentic Systems 2.1 API Contract",
        "",
        "Generated by `scripts/generate_api_contract.py` from the runtime manifest.",
        "Do not edit this file by hand.",
        "",
        "## Contract Summary",
        "",
        f"- Schema: `{manifest['schema_version']}`",
        f"- Stable exports: `{manifest['export_count']}`",
        f"- Export and member IDs: `{manifest['entry_count']}`",
        f"- Shared scenarios: `{manifest['scenario_count']}`",
        f"- Checksum: `{manifest['checksum']}`",
        "- Notebook: `tutorials/api/14_api_contract_matrix.ipynb`",
        "",
        "## Traceability",
        "",
        "Every heading below is one canonical ID shared by Source, API,",
        "documentation, the reference notebook and pytest.",
        "",
    ]
    lines.extend(
        [
            "### Scenario registry",
            "",
            "| Scenario | Notebooks | API IDs |",
            "|---|---|---|",
        ]
    )
    for scenario in manifest["scenarios"]:
        lines.append(
            f"| `{scenario['id']}` | "
            f"{'<br>'.join(scenario['notebooks'])} | "
            f"{'<br>'.join(scenario['api_ids'])} |"
        )
    lines.extend(
        [
            "",
            "## API IDs",
            "",
        ]
    )

    for entry in manifest["entries"]:
        signature = entry["signature"] or "n/a"
        lines.extend(
            [
                f"## `{entry['id']}`",
                "",
                re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", entry["summary"]),
                "",
                f"- Export: `{entry['export']}`",
                f"- Member: `{entry['member'] or 'n/a'}`",
                f"- Kind: `{entry['kind']}`",
                f"- Tier: `{entry['tier']}`",
                f"- Signature: `{signature}`",
                f"- Source: `{_source_path(entry['source'])}` (`{entry['source']}`)",
                f"- Contract ID: `{entry['id']}`",
                "",
            ]
        )
    return "\n".join(lines).rstrip() + "\n"


def _md(source: str) -> dict[str, Any]:
    return {"cell_type": "markdown", "metadata": {}, "source": source.splitlines(True)}


def _code(source: str) -> dict[str, Any]:
    return {
        "cell_type": "code",
        "execution_count": None,
        "metadata": {},
        "outputs": [],
        "source": source.splitlines(True),
    }


