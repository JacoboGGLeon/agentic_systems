def _outputs() -> dict[Path, str]:
    manifest = toolkit.api_contract()
    return {
        API_DOC: _api_doc(API_DOC.read_text(encoding="utf-8"), manifest),
        CONTRACT_DOC: _contract_doc(manifest),
        CONTRACT_NOTEBOOK: _notebook(manifest),
        TUTORIAL_README: _tutorial_readme(manifest),
    }


def generate(*, check: bool) -> int:
    drift: list[Path] = []
    for path, content in _outputs().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == content:
            continue
        if check:
            drift.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
            print(f"generated {path.relative_to(ROOT)}")
    if drift:
        print("API contract drift:")
        for path in drift:
            print(f"- {path}")
        return 1
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    return generate(check=parser.parse_args().check)


if __name__ == "__main__":
    raise SystemExit(main())
