"""Validate current notebooks and generate deterministic Markdown reading views."""
import argparse
import json
from pathlib import Path
from nbconvert import MarkdownExporter
import nbformat

ROOT = Path(__file__).resolve().parents[1]


def current_notebooks():
    return sorted([* (ROOT / 'tutorials').rglob('*.ipynb'),
                   *(p for p in (ROOT / 'examples').rglob('*.ipynb') if 'history' not in p.parts)])


def render(check=False):
    rows = []
    for path in current_notebooks():
        notebook = nbformat.read(path, as_version=4)
        nbformat.validate(notebook)
        text, resources = MarkdownExporter().from_notebook_node(notebook)
        relative = path.relative_to(ROOT).as_posix()
        header = ('<!-- Generated by scripts/render_notebook_docs.py; edit the notebook instead. -->\n'
                  f'[Notebook source]({path.name}) · [Download notebook](https://raw.githubusercontent.com/JacoboGGLeon/agentic_systems/main/{relative})\n\n')
        target = path.with_suffix('.md')
        expected = header + text
        if check:
            assert target.is_file() and target.read_text(encoding='utf-8') == expected, target
        else:
            target.write_text(expected, encoding='utf-8')
        assert not resources.get('outputs'), f'External output assets need explicit handling: {path}'
        rows.append({'notebook': relative, 'reading_view': target.relative_to(ROOT).as_posix()})
    print(json.dumps({'validated': len(rows), 'markdown_views': len(rows)}))
    return rows


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    render(parser.parse_args().check)
